async function assertExactLinuxArm64OciIndex(
  rawIndex: string,
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
): Promise<void> {
  const matchedRaw = await matchingOciIndexBytes(
    rawIndex,
    receipt.candidate.oci.indexDigest,
  );
  if (matchedRaw === undefined) {
    throw new Error(
      "The inspected OCI index digest is not the receipt OCI index digest.",
    );
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(matchedRaw);
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new TypeError(`OCI index must be valid JSON: ${detail}`);
  }
  const root = jsonObject(parsed, "OCI index");
  const manifests = root.manifests;
  if (!Array.isArray(manifests)) {
    throw new TypeError("OCI index manifests must be an array.");
  }
  const arm64 = manifests.filter((item) => {
    if (item === null || typeof item !== "object" || Array.isArray(item)) {
      return false;
    }
    const platform = (item as Record<string, unknown>).platform;
    if (
      platform === null || typeof platform !== "object" || Array.isArray(platform)
    ) {
      return false;
    }
    const body = platform as Record<string, unknown>;
    return body.os === "linux" && body.architecture === "arm64";
  });
  if (arm64.length !== 1) {
    throw new Error(
      "OCI index must contain exactly one linux/arm64 child manifest.",
    );
  }
  const child = arm64[0] as Record<string, unknown>;
  if (child.digest !== receipt.candidate.oci.platformManifestDigest) {
    throw new Error(
      "The OCI index linux/arm64 child digest is not the receipt platform-manifest digest.",
    );
  }
}

function assertExactCandidateDockerSource(
  inspection: DockerSourceInspection,
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
): void {
  const expected = receipt.candidate.expectedRuntime;
  const digestMatches = inspection.repoDigests.some((digest) =>
    samePinnedRepositoryDigest(
      digest,
      receipt.candidate.oci.platformManifestReference,
    )
  );
  if (
    inspection.os !== "linux" ||
    inspection.architecture !== "arm64" ||
    inspection.user !== expected.user ||
    !stringArraysEqual(inspection.entrypoint, expected.entrypoint) ||
    !digestMatches ||
    (expected.labels !== undefined &&
      !Object.entries(expected.labels).every(([name, value]) =>
        inspection.labels[name] === value
      ))
  ) {
    throw new Error(
      "The Docker source image is not the exact linux/arm64 first-party candidate.",
    );
  }
}

function assertExactCandidateMicrosandboxInspection(
  image: MicrosandboxImageInspection,
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
  expectedReference: string,
  expectedDigest: string | undefined,
): string {
  const expected = receipt.candidate.expectedRuntime;
  if (!SHA256.test(image.manifestDigest)) {
    throw new Error(
      "The cached Microsandbox candidate is not identified by a lowercase sha256 digest.",
    );
  }
  if (
    image.reference !== expectedReference ||
    image.os !== "linux" ||
    image.architecture !== "arm64" ||
    image.user !== expected.user ||
    !stringArraysEqual(image.entrypoint, expected.entrypoint) ||
    (expectedDigest !== undefined && image.manifestDigest !== expectedDigest)
  ) {
    throw new Error(
      "The cached Microsandbox candidate is not the inspected first-party candidate.",
    );
  }
  return image.manifestDigest;
}

function buildImportRecord(
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
  imported: {
    readonly candidateReference: string;
    readonly manifestDigest: string;
    readonly status: "imported" | "already-cached";
  },
): FirstPartyMicrosandboxImageCandidateImportRecord {
  return Object.freeze({
    schemaVersion: FIRST_PARTY_MICROSANDBOX_IMAGE_CANDIDATE_IMPORT_RECORD_SCHEMA,
    candidate: Object.freeze({
      physicalImageId: receipt.candidate.physicalImageId,
      imageName: receipt.candidate.imageName,
      oci: receipt.candidate.oci,
      microsandbox: Object.freeze({
        candidateReference: imported.candidateReference,
        manifestDigest: imported.manifestDigest,
      }),
      locatorTag: receipt.candidate.locatorTag,
      locatorReference: receipt.candidate.locatorReference,
      git: receipt.candidate.git,
      qualificationTarget: receipt.candidate.qualificationTarget,
    }),
    identities: Object.freeze({
      ociIndexDigest: receipt.candidate.oci.indexDigest,
      ociPlatformManifestDigest: receipt.candidate.oci.platformManifestDigest,
      microsandboxManifestDigest: imported.manifestDigest,
    }),
    inputMatrix: Object.freeze({
      fingerprint: receipt.inputMatrix.fingerprint,
      schemaVersion: receipt.inputMatrix.schemaVersion,
    }),
    artifactCompliance: Object.freeze({
      licence: "unresolved" as const,
      anonymousPull: "not-run" as const,
      runtimeQualification: "not-run" as const,
      eligibleForPromotion: false as const,
      sbom: "requested" as const,
      provenance: "requested" as const,
    }),
    import: Object.freeze({
      status: imported.status,
      hostArchitecture: "arm64" as const,
      pullPolicy: PULL_POLICY_NEVER,
    }),
  });
}

function importRecordFileName(
  record: FirstPartyMicrosandboxImageCandidateImportRecord,
): string {
  return [
    hexDigest(record.identities.ociIndexDigest),
    hexDigest(record.identities.ociPlatformManifestDigest),
    hexDigest(record.identities.microsandboxManifestDigest),
  ].join("-") + ".json";
}

function hexDigest(value: string): string {
  return value.slice("sha256:".length);
}

async function matchingOciIndexBytes(
  rawIndex: string,
  expectedDigest: string,
): Promise<string | undefined> {
  const candidates = rawIndex.endsWith("\n")
    ? [rawIndex, rawIndex.slice(0, -1)]
    : [rawIndex];
  for (const candidate of candidates) {
    const digest = `sha256:${await sha256Hex(new TextEncoder().encode(candidate))}`;
    if (digest === expectedDigest) return candidate;
  }
  return undefined;
}

async function requireDockerInspection(
  ports: FirstPartyMicrosandboxImageCandidateImportPorts,
  reference: string,
): Promise<unknown> {
  const raw = await ports.inspectDockerImage(reference);
  if (raw === undefined) {
    throw new Error("The Docker platform-manifest image is absent after pull.");
  }
  return raw;
}

async function lookupCachedRuntimeImage(
  ports: FirstPartyMicrosandboxImageCandidateImportPorts,
  reference: string,
): Promise<MicrosandboxImageInspection | undefined> {
  try {
    return await ports.inspectCachedImage(reference);
  } catch (error) {
    if (ports.isImageNotFound(error)) return undefined;
    throw error;
  }
}

async function removeOwnedCandidateReference(
  ports: FirstPartyMicrosandboxImageCandidateImportPorts,
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
  stagingReference: string,
  reference: string,
): Promise<void> {
  assertOwnedCandidateCacheReference(reference, receipt, stagingReference);
  await ports.removeExactCachedImage(reference);
}

function wrapIncoherentPreexistingCandidate(error: unknown): Error {
  const detail = error instanceof Error ? error.message : String(error);
  return new Error(
    `An incoherent pre-existing first-party Microsandbox candidate must not be deleted: ${detail}`,
  );
}

function assertOwnedCandidateCacheReference(
  reference: string,
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
  stagingReference: string,
): void {
  const catalogPin = receipt.candidate.qualificationTarget.imageReference;
  if (reference === catalogPin) {
    throw new Error(
      "First-party candidate import must not remove the active catalogue pin.",
    );
  }
  const candidatePrefix = `${
    firstPartyMicrosandboxImageCandidateName(receipt.candidate.physicalImageId)
  }@sha256:`;
  if (reference !== stagingReference && !reference.startsWith(candidatePrefix)) {
    throw new Error(
      "First-party candidate import may remove only its staging or final candidate reference.",
    );
  }
}

function assertNonCatalogLoadTag(tag: string, catalogPin: string): void {
  if (tag === catalogPin) {
    throw new Error(
      "First-party candidate import must not load under the active catalogue pin.",
    );
  }
}

function assertRequestedLoadReference(
  handles: readonly MicrosandboxImageImportHandle[],
  expectedReference: string,
  role: "staging" | "final candidate",
): void {
  if (!handles.some((handle) => handle.reference === expectedReference)) {
    throw new Error(
      `Microsandbox archive load did not apply the requested ${role} reference.`,
    );
  }
}

function assertNoCatalogPinReturnedByLoad(
  handles: readonly MicrosandboxImageImportHandle[],
  catalogPin: string,
): void {
  if (
    handles.some((handle) =>
      handle.reference === catalogPin ||
      samePinnedRepositoryDigest(handle.reference, catalogPin)
    )
  ) {
    throw new Error(
      "Microsandbox archive load returned the active catalogue pin; the candidate import is refused.",
    );
  }
}

function assertDistinctFromCatalogPin(
  reference: string,
  catalogPin: string,
  label: string,
): void {
  if (reference === catalogPin) {
    throw new Error(
      `First-party candidate ${label} must not equal the active catalogue pin.`,
    );
  }
}

function assertLiteralNotRunCompliance(
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
): void {
  if (
    receipt.artifactCompliance.runtimeQualification !== "not-run" ||
    receipt.artifactCompliance.eligibleForPromotion !== false
  ) {
    throw new TypeError(
      "Candidate import requires runtimeQualification=not-run and eligibleForPromotion=false.",
    );
  }
}

function assertHostArchitecture(hostArchitecture: string): void {
  if (hostArchitecture !== "arm64") {
    throw new Error(
      "First-party Microsandbox candidate import is reviewed only for native linux/arm64.",
    );
  }
}

function assertSha256(value: string, label: string): void {
  if (!SHA256.test(value)) {
    throw new TypeError(`${label} must be an exact lowercase sha256 digest.`);
  }
}

function assertStagingToken(value: string): void {
  if (!STAGING_TOKEN.test(value)) {
    throw new TypeError(
      "First-party candidate staging token must be a server-generated lowercase nonce.",
    );
  }
}

function stagingLocatorPrefix(
  receipt: FirstPartyMicrosandboxImageCandidateReceipt,
): string {
  return receipt.candidate.locatorTag.slice(
    0,
    MAXIMUM_STAGING_LOCATOR_PREFIX_LENGTH,
  );
}

function createFirstPartyMicrosandboxImageCandidateStagingToken(): string {
  return crypto.randomUUID();
}

function jsonObject(value: unknown, label: string): Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new TypeError(`${label} must be a JSON object.`);
  }
  return value as Record<string, unknown>;
}

function stringArraysEqual(
  left: readonly string[] | null,
  right: readonly string[],
): boolean {
  return left !== null && left.length === right.length &&
    left.every((value, index) => value === right[index]);
}

async function inspectOciIndex(reference: string): Promise<string> {
  if (!reference.includes("@sha256:") || reference.endsWith(":latest")) {
    throw new TypeError(
      "OCI index inspect requires an exact digest-pinned reference.",
    );
  }
  const output = await docker([
    "buildx",
    "imagetools",
    "inspect",
    "--raw",
    reference,
  ]);
  if (!output.success) {
    throw new Error(
      `docker buildx imagetools inspect failed: ${decode(output.stderr).slice(-2_000)}`,
    );
  }
  return decode(output.stdout);
}

async function inspectDockerImage(reference: string): Promise<unknown | undefined> {
  const output = await docker([
    "image",
    "inspect",
    "--format",
    "{{json .}}",
    reference,
  ]);
  if (!output.success) return undefined;
  return JSON.parse(decode(output.stdout)) as unknown;
}

async function pullByDigest(reference: string): Promise<void> {
  if (!reference.includes("@sha256:") || reference.endsWith(":latest")) {
    throw new TypeError(
      "First-party candidate pull requires an exact digest-pinned reference.",
    );
  }
  const output = await docker(["pull", reference]);
  if (!output.success) {
    throw new Error(`docker pull failed: ${decode(output.stderr).slice(-2_000)}`);
  }
}

async function saveDockerImage(reference: string, archivePath: string): Promise<void> {
  const output = await docker(["image", "save", "-o", archivePath, reference]);
  if (!output.success) {
    throw new Error(
      `docker image save failed: ${decode(output.stderr).slice(-2_000)}`,
    );
  }
}

async function createAllowedCandidateArchive(): Promise<
  FirstPartyMicrosandboxTemporaryArchive
> {
  const directory = assertAllowedFirstPartyBootstrapTempPath(
    await Deno.makeTempDir({
      dir: "/tmp",
      prefix: "casys-first-party-microsandbox-candidate-",
    }),
  );
  return Object.freeze({
    directory,
    archivePath: `${directory}/image.tar`,
    cleanup: () => Deno.remove(directory, { recursive: true }),
  });
}

async function docker(args: readonly string[]): Promise<Deno.CommandOutput> {
  return await new Deno.Command("docker", {
    args: [...args],
    stdin: "null",
    stdout: "piped",
    stderr: "piped",
  }).output();
}

function decode(bytes: Uint8Array): string {
  return new TextDecoder().decode(bytes);
}
