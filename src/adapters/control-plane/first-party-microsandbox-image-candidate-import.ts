/**
 * Maintainer-only import/inspection of one first-party Microsandbox image
 * candidate. The only identity input is an exact repository receipt already
 * bound to the current server-owned distribution matrix.
 *
 * Three immutable provenance fields stay separately recorded:
 * 1. OCI index digest from Buildx
 * 2. linux/arm64 OCI platform-manifest digest pulled from Docker
 * 3. Microsandbox manifest digest observed after docker save + Image.load
 *
 * Their hash text can coincide; neither a comparison nor a record collapses
 * the three provenance fields into one identity.
 *
 * This path never calls acquireFirstPartyMicrosandboxImage (that imports under
 * the active catalogue pin). Microsandbox SDK 0.6.8 has no tag/relabel API:
 * staging is Image.load(archive, { tag: staging }), then exact Image.remove of
 * that staging reference, then a second Image.load of the same archive with
 * tag casys/first-party-candidate-<physicalImageId>@sha256:<observed-msb-digest>.
 * That second load is a re-import that applies the candidate reference, not an
 * in-place retag.
 */

