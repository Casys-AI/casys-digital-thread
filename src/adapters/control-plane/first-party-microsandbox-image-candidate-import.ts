  "first-party-microsandbox-image-candidate-import-plan/2.0" as const;

export const FIRST_PARTY_MICROSANDBOX_IMAGE_CANDIDATE_IMPORT_RECORD_DIRECTORY =
  "state/local/first-party-microsandbox-image-candidate-import" as const;

const SHA256 = /^sha256:[0-9a-f]{64}$/u;
const PULL_POLICY_NEVER = "never" as const;
const CANDIDATE_REPOSITORY_PREFIX = "casys/first-party-candidate-" as const;
const STAGING_REPOSITORY_PREFIX = "casys/first-party-candidate-staging-" as const;
const STAGING_TOKEN = /^[a-z0-9](?:[a-z0-9-]{0,63})?$/u;
const DOCKER_TAG = /^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$/u;
const MAXIMUM_STAGING_LOCATOR_PREFIX_LENGTH = 63;

export interface FirstPartyMicrosandboxImageCandidateImportPorts {
  readonly hostArchitecture: string;
  /**
   * Invocation-owned nonce. It is generated by the server/composition at run
   * time, never supplied by a caller and never persisted in the factual
   * candidate record.
   */
  createStagingToken(): string;
  inspectOciIndex(reference: string): Promise<string>;
  pullByDigest(reference: string): Promise<void>;
  inspectDockerImage(reference: string): Promise<unknown | undefined>;
  saveDockerImage(reference: string, archivePath: string): Promise<void>;
  loadImageFromArchive(
    archivePath: string,
    tag: string,
  ): Promise<readonly MicrosandboxImageImportHandle[]>;
  inspectCachedImage(reference: string): Promise<MicrosandboxImageInspection>;
  isImageNotFound(error: unknown): boolean;
  /**
   * Exact Microsandbox cached-image removal. No force, prune, or volume.
   * Callers of this port from the candidate-import flow may pass only the
   * staging reference or a final candidate this flow just imported.
   */
  removeExactCachedImage(reference: string): Promise<void>;
  createTemporaryArchiveDirectory(): Promise<FirstPartyMicrosandboxTemporaryArchive>;
  writeImportRecord(
    record: FirstPartyMicrosandboxImageCandidateImportRecord,
  ): Promise<void>;
}

